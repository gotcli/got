package cmd

import (
	"errors"
	"fmt"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/gotcli/got/internal/upgrade"
	"github.com/spf13/cobra"
)

func newUpgradeCommand(cfg *config) *cobra.Command {
	var dryRun, force bool
	command := &cobra.Command{
		Use:   "upgrade",
		Short: "Apply fixes from newer GOT versions to the current project",
		Long: `Bring a project generated by an older GOT version up to date.

Each upgrade step inspects the project files to decide whether it applies, so
projects created before got-project.json existed are supported. A step only
rewrites code that still matches what GOT generated; when you have changed that
code, the step is reported as a manual action with instructions and no file is
touched. From a workspace root, every service is upgraded.

Files with uncommitted Git changes are never overwritten unless --force is
given, so every upgrade can be reviewed with "git diff". Use --dry-run first.`,
		Example: `  got upgrade --dry-run
  got upgrade
  git diff`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			projects, workspace, err := discoverDoctorProjects(cfg.cwd)
			if err != nil {
				return err
			}
			out := cmd.OutOrStdout()
			pending, manual := 0, 0
			type target struct {
				path, label string
				plan        func() ([]upgrade.Result, error)
			}
			var targets []target
			if workspace {
				targets = append(targets, target{cfg.cwd, "workspace", func() ([]upgrade.Result, error) { return upgrade.PlanWorkspace(cfg.cwd) }})
			}
			for _, project := range projects {
				path := project.Path
				targets = append(targets, target{path, filepath.Base(path), func() ([]upgrade.Result, error) { return upgrade.Plan(path, cfg.version) }})
			}
			for index, project := range targets {
				results, err := project.plan()
				if err != nil {
					return fmt.Errorf("%s: %w", project.path, err)
				}
				if index > 0 {
					fmt.Fprintln(out)
				}
				if workspace {
					fmt.Fprintf(out, "# %s\n", project.label)
				}
				var files []string
				for _, result := range results {
					files = append(files, result.Files...)
				}
				if !dryRun && !force && len(files) > 0 {
					dirty, err := uncommittedFiles(project.path, files)
					if err != nil {
						return err
					}
					if len(dirty) > 0 {
						return fmt.Errorf("%s: refusing to overwrite files with uncommitted changes: %s (commit or stash them, or use --force)", project.path, strings.Join(dirty, ", "))
					}
				}
				for _, result := range results {
					switch result.Status {
					case upgrade.StatusPending:
						pending++
						label := "applied"
						if dryRun {
							label = "would apply"
						}
						fmt.Fprintf(out, "  [%s] %s: %s (%s)\n", label, result.ID, result.Description, strings.Join(result.Files, ", "))
					case upgrade.StatusManual:
						manual++
						fmt.Fprintf(out, "  [manual] %s: %s\n", result.ID, result.Detail)
					default:
						fmt.Fprintf(out, "  [ok] %s\n", result.ID)
					}
				}
				if dryRun {
					continue
				}
				if err := upgrade.Apply(project.path, results); err != nil {
					return err
				}
			}
			fmt.Fprintln(out)
			switch {
			case pending == 0 && manual == 0:
				fmt.Fprintln(out, "project is up to date")
			case dryRun:
				fmt.Fprintf(out, "dry run: %d changes would be applied, %d need manual action\n", pending, manual)
			default:
				fmt.Fprintf(out, "applied %d changes, %d need manual action; review with \"git diff\" and run \"go build ./...\"\n", pending, manual)
			}
			return nil
		},
	}
	command.Flags().BoolVar(&dryRun, "dry-run", false, "show what would change without writing")
	command.Flags().BoolVar(&force, "force", false, "overwrite files even when they have uncommitted Git changes")
	return command
}

// uncommittedFiles returns which of files have uncommitted changes. Outside a
// Git repository, or without git installed, nothing can be checked.
func uncommittedFiles(project string, files []string) ([]string, error) {
	if _, err := exec.LookPath("git"); err != nil {
		return nil, nil
	}
	args := append([]string{"-C", project, "status", "--porcelain", "--"}, files...)
	output, err := exec.Command("git", args...).Output()
	if err != nil {
		var exitError *exec.ExitError
		if errors.As(err, &exitError) {
			return nil, nil // not a Git repository
		}
		return nil, err
	}
	var dirty []string
	// Porcelain lines start with a two-letter status that may begin with a space.
	for _, line := range strings.Split(strings.TrimRight(string(output), "\n"), "\n") {
		if len(line) > 3 && !strings.HasPrefix(line, "??") {
			dirty = append(dirty, strings.TrimSpace(line[3:]))
		}
	}
	return dirty, nil
}
